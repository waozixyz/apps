#!/usr/bin/env python3
"""Compile the shared Apps UI's complete translations into portable text."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
locales = {path.stem: json.loads(path.read_text()) for path in sorted((ROOT / 'ui/locales').glob('*.json'))}
keys = set(locales['en'])
for locale, values in locales.items():
    if set(values) != keys or not all(isinstance(value, str) and value for value in values.values()):
        raise SystemExit(f'Incomplete translation: {locale}')
text = '// Generated by scripts/generate-ui-locales.py from all UI translations.\n'
text += 'AppsLabel :: (locale: string, key: string) -> string {\n'
for locale, values in locales.items():
    if locale == 'en':
        continue
    text += f'    if locale == {json.dumps(locale)} {{\n'
    for key, value in values.items():
        text += f'        if key == {json.dumps(key)} {{ return {json.dumps(value, ensure_ascii=False)} }}\n'
    text += '    }\n'
for key, value in locales['en'].items():
    text += f'    if key == {json.dumps(key)} {{ return {json.dumps(value, ensure_ascii=False)} }}\n'
text += '    return key\n}\n'
output = ROOT / 'ui/words.zi'
if '--check' in sys.argv:
    if not output.exists() or output.read_text() != text:
        raise SystemExit('UI translations are stale; run scripts/generate-ui-locales.py')
else:
    output.write_text(text)
